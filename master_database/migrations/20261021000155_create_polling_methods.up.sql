CREATE TABLE polling_methods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,

    CONSTRAINT ck_polling_methods_code_format
        CHECK (code ~ '^[a-z]+(_[a-z]+)*$'),
    CONSTRAINT ck_polling_methods_name_not_blank
        CHECK (length(btrim(name)) > 0)
);

CREATE UNIQUE INDEX uq_polling_methods_code ON polling_methods (code);
CREATE INDEX idx_polling_methods_is_active ON polling_methods (is_active);
CREATE INDEX idx_polling_methods_deleted_at ON polling_methods (deleted_at);

COMMENT ON TABLE polling_methods IS
    'Stable polling behaviors. Initial codes: agree_disagree, rating (integer 0-10), selection (one topic option). Retiring a method preserves existing topic references.';
