CREATE TABLE provinces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kemendagri_code VARCHAR(2) NOT NULL,
    name TEXT NOT NULL,
    boundary geometry(MultiPolygon,4326) NOT NULL,
    boundary_source TEXT NOT NULL,
    boundary_reference_date DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ
);

-- Codes remain reserved after soft deletion.
CREATE UNIQUE INDEX uq_provinces_kemendagri_code ON provinces (kemendagri_code);
CREATE INDEX idx_provinces_deleted_at ON provinces (deleted_at);
CREATE INDEX idx_provinces_is_active ON provinces (is_active);
CREATE INDEX idx_provinces_name_trgm ON provinces USING GIN (name gin_trgm_ops);
CREATE INDEX idx_provinces_boundary_gist ON provinces USING GIST (boundary);

COMMENT ON TABLE provinces IS 'Indonesian province reference data with canonical WGS84 boundaries.';
COMMENT ON COLUMN provinces.kemendagri_code IS
    'Two-digit Kemendagri province code, separate from BPS codes.';
COMMENT ON COLUMN provinces.boundary IS
    '2D WGS84 MultiPolygon; X is longitude and Y is latitude. Topological validity is not enforced by the database.';
COMMENT ON COLUMN provinces.boundary_source IS
    'Dataset/publisher reference, version or release identifier, and attribution.';
COMMENT ON COLUMN provinces.boundary_reference_date IS
    'Effective/reference date of the source boundaries, not the import timestamp.';
