CREATE TYPE city_kind AS ENUM ('city', 'regency');

CREATE TABLE cities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    province_id BIGINT NOT NULL,
    kemendagri_code VARCHAR(5) NOT NULL,
    kind city_kind NOT NULL,
    name TEXT NOT NULL,
    boundary geometry(MultiPolygon,4326) NOT NULL,
    boundary_source TEXT NOT NULL,
    boundary_reference_date DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,

    CONSTRAINT fk_cities_province
        FOREIGN KEY (province_id) REFERENCES provinces (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_cities_code_format
        CHECK (kemendagri_code ~ '^[0-9]{2}[.][0-9]{2}$'),
    CONSTRAINT ck_cities_name_not_blank
        CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_cities_boundary_source_not_blank
        CHECK (length(btrim(boundary_source)) > 0),
    CONSTRAINT ck_cities_boundary_valid
        CHECK (ST_IsValid(boundary) AND NOT ST_IsEmpty(boundary))
);

-- Codes remain reserved after soft deletion. The parent ID leads the listing index.
CREATE UNIQUE INDEX uq_cities_kemendagri_code ON cities (kemendagri_code);
CREATE INDEX idx_cities_province_kind_name ON cities (province_id, kind, name, id);
CREATE INDEX idx_cities_boundary_gist ON cities USING GIST (boundary);

COMMENT ON TABLE cities IS
    'Second-level regions: cities (kota) and regencies (kabupaten), including administrative regions.';
COMMENT ON COLUMN cities.kemendagri_code IS
    'Full Kemendagri code in PP.CC form; imports must verify PP against the parent province code.';
COMMENT ON COLUMN cities.boundary IS
    'Valid, nonempty 2D WGS84 MultiPolygon; geographic consistency with the province is checked at import.';
COMMENT ON COLUMN cities.boundary_source IS
    'Dataset/publisher reference, version or release identifier, and attribution.';
COMMENT ON COLUMN cities.boundary_reference_date IS
    'Effective/reference date of the source boundaries, not the import timestamp.';
